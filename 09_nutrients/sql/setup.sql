CREATE TABLE IF NOT EXISTS foods (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    calories_per_100g DOUBLE PRECISION NOT NULL,
    protein_per_100g DOUBLE PRECISION NOT NULL,
    icon_emoji VARCHAR(10),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_foods_id
    ON foods (id);


CREATE TABLE IF NOT EXISTS diary_entries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    health_rating VARCHAR(50) NOT NULL,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_diary_entries_id
    ON diary_entries (id);


CREATE TABLE IF NOT EXISTS food_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diary_entry_id INTEGER NOT NULL,
    food_id INTEGER NOT NULL,
    grams_eaten DOUBLE PRECISION NOT NULL,
    eaten_day DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_food_logs_diary_entry
        FOREIGN KEY (diary_entry_id)
        REFERENCES diary_entries(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_food_logs_food
        FOREIGN KEY (food_id)
        REFERENCES foods(id)
);

CREATE INDEX IF NOT EXISTS ix_food_logs_id
    ON food_logs (id);